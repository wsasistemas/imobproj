-- ======================================================================= estrutura

create table if not exists imobproj.tr_trilhas (
  id            bigint      generated by default as identity primary key,
  codigo        text        not null unique check (codigo ~ '^[a-z][a-z0-9_]{1,30}$'),
  nome          text        not null check (length(btrim(nome)) between 3 and 60),
  descricao     text        not null default '' check (length(descricao) <= 200),
  padrao        boolean     not null default false,   -- trilha de quem não tem perfil com trilha
  ordem         int         not null default 0,
  atualizado_em timestamptz not null default now()
);
create unique index if not exists tr_trilhas_padrao_uidx on imobproj.tr_trilhas (padrao) where padrao;

-- Perfil de acesso → trilha (um perfil segue uma trilha só). Sem FK para perfis: o perfil pode ser
-- criado depois e, se for excluído, a linha só deixa de valer.
create table if not exists imobproj.tr_trilha_perfis (
  perfil    text   primary key check (perfil ~ '^[a-z_][a-z0-9_]{0,40}$'),
  trilha_id bigint not null references imobproj.tr_trilhas (id) on delete cascade
);
create index if not exists tr_trilha_perfis_trilha_idx on imobproj.tr_trilha_perfis (trilha_id);

create table if not exists imobproj.tr_modulos (
  id             bigint      generated by default as identity primary key,
  codigo         text        not null unique check (codigo ~ '^[a-z0-9_]{1,30}$'),
  titulo         text        not null check (length(btrim(titulo)) between 3 and 90),
  descricao      text        not null default '' check (length(descricao) <= 240),
  papel          text        not null check (papel in ('gerencia', 'campo', 'atende', 'cliente')),
  minutos        int         not null default 3 check (minutos between 1 and 60),
  rota_demo      text        not null default '/' check (rota_demo ~ '^/'),
  celular        boolean     not null default false,
  pergunta       text        not null check (length(btrim(pergunta)) between 5 and 200),
  opcoes         jsonb       not null check (jsonb_typeof(opcoes) = 'array' and jsonb_array_length(opcoes) between 2 and 5),
  resposta       int         not null check (resposta >= 0),
  status         text        not null default 'rascunho' check (status in ('rascunho', 'publicado')),
  ordem          int         not null default 0,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  atualizado_por uuid,
  check (resposta < jsonb_array_length(opcoes))
);

create table if not exists imobproj.tr_trilha_modulos (
  trilha_id bigint not null references imobproj.tr_trilhas (id) on delete cascade,
  modulo_id bigint not null references imobproj.tr_modulos (id) on delete cascade,
  ordem     int    not null default 0,
  primary key (trilha_id, modulo_id)
);
create index if not exists tr_trilha_modulos_modulo_idx on imobproj.tr_trilha_modulos (modulo_id);

create table if not exists imobproj.tr_passos (
  id            bigint      generated by default as identity primary key,
  modulo_id     bigint      not null references imobproj.tr_modulos (id) on delete cascade,
  ordem         int         not null,
  tela          text        not null check (tela ~ '^[a-z0-9-]{1,40}$'),   -- public/treinamento/<tela>.webp
  titulo        text        not null check (length(btrim(titulo)) between 2 and 60),
  texto         text        not null check (length(btrim(texto)) between 2 and 400),
  -- Contorno do elemento explicado: [x, y, largura, altura] em % da tela capturada.
  alvo          numeric[]   not null check (array_length(alvo, 1) = 4 and 0 <= all (alvo) and 100 >= all (alvo)),
  posicao       text        not null default 'auto' check (posicao in ('auto', 'direita', 'esquerda', 'abaixo', 'acima')),
  atualizado_em timestamptz not null default now(),
  unique (modulo_id, ordem) deferrable initially deferred
);

create table if not exists imobproj.tr_progresso (
  usuario_id    uuid        not null references imobproj.profiles (id) on delete cascade,
  modulo_id     bigint      not null references imobproj.tr_modulos (id) on delete cascade,
  passo_atual   int         not null default 0 check (passo_atual >= 0),
  iniciado_em   timestamptz not null default now(),
  concluido_em  timestamptz,
  atualizado_em timestamptz not null default now(),
  primary key (usuario_id, modulo_id)
);
create index if not exists tr_progresso_modulo_idx on imobproj.tr_progresso (modulo_id);

