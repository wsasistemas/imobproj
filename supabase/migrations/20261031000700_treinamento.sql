  raise exception '%', p_msg using errcode = 'P0001';
end;
$$;

/** Pessoa logada com cadastro ativo no IMOBPROJ. */
create or replace function imobproj.tr_exigir_login()
returns uuid
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is null
     or not exists (select 1 from imobproj.profiles p where p.id = (select auth.uid())) then
    perform imobproj.tr_erro('Entre no IMOBPROJ para ver os treinamentos.');
  end if;
  return (select auth.uid());
end;
$$;

