security definer
set search_path = ''
as $$
  select coalesce((select tp.trilha_id from imobproj.tr_trilha_perfis tp where tp.perfil = p_perfil),
                  (select t.id from imobproj.tr_trilhas t where t.padrao));
$$;

/** Módulos publicados de uma trilha, na ordem da trilha. */
create or replace function imobproj.tr_modulos_visiveis(p_trilha bigint)
returns setof bigint
language sql
stable
security definer
set search_path = ''
as $$
  select m.id
  from imobproj.tr_trilha_modulos tm
  join imobproj.tr_modulos m on m.id = tm.modulo_id
  where tm.trilha_id = p_trilha and m.status = 'publicado'
  order by tm.ordem, m.ordem, m.id;
$$;

create or replace function imobproj.tr_pode_ver_modulo(p_usuario uuid, p_modulo bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select imobproj.tr_eh_gestor()
      or p_modulo in (select imobproj.tr_modulos_visiveis(
                        imobproj.tr_trilha_do_perfil(imobproj.tr_perfil_do_usuario(p_usuario))));
$$;

create or replace function imobproj.tr_modulo_resumo(p_modulo bigint, p_usuario uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'id', m.id, 'codigo', m.codigo, 'titulo', m.titulo, 'descricao', m.descricao, 'papel', m.papel,
    'minutos', m.minutos, 'rotaDemo', m.rota_demo, 'celular', m.celular, 'status', m.status,
    'passos', (select count(*) from imobproj.tr_passos p where p.modulo_id = m.id),
    'capa', (select p.tela from imobproj.tr_passos p where p.modulo_id = m.id order by p.ordem limit 1),
    'passoAtual', coalesce(pr.passo_atual, 0), 'concluidoEm', pr.concluido_em, 'iniciado', pr.usuario_id is not null)
  from imobproj.tr_modulos m
  left join imobproj.tr_progresso pr on pr.modulo_id = m.id and pr.usuario_id = p_usuario
  where m.id = p_modulo;
$$;

-- ======================================================================= quem faz o treinamento

/**
 * Meus treinamentos: a trilha do perfil da pessoa e os módulos dela, com o progresso.
 * p_perfil (só super admin): "ver como" as pessoas daquele perfil veem.
 */
create or replace function imobproj.tr_meus_treinamentos(p_perfil text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid uuid := imobproj.tr_exigir_login();
  v_simula boolean := p_perfil is not null;
  v_perfil text;
  v_trilha bigint;
begin
  if v_simula then
    perform imobproj.tr_exigir_gestor();
    v_perfil := p_perfil;
  else
    v_perfil := imobproj.tr_perfil_do_usuario(v_uid);
  end if;
  v_trilha := imobproj.tr_trilha_do_perfil(v_perfil);
  return jsonb_build_object(
    'perfil', (select jsonb_build_object('chave', pf.chave, 'nome', pf.nome) from imobproj.perfis pf where pf.chave = v_perfil),
    'semPerfil', not v_simula and v_perfil is null,
    'trilha', (select jsonb_build_object('id', t.id, 'codigo', t.codigo, 'nome', t.nome, 'descricao', t.descricao, 'padrao', t.padrao)
               from imobproj.tr_trilhas t where t.id = v_trilha),
    'modulos', coalesce((select jsonb_agg(imobproj.tr_modulo_resumo(x.id, v_uid))
                         from imobproj.tr_modulos_visiveis(v_trilha) as x (id)), '[]'));
end;
$$;

/** O módulo para o tour: passos e opções da pergunta, sem o gabarito. */
create or replace function imobproj.tr_modulo(p_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid uuid := imobproj.tr_exigir_login();
begin
  if not exists (select 1 from imobproj.tr_modulos m where m.id = p_id) then
    perform imobproj.tr_erro('Treinamento não encontrado.');
  end if;
  if not imobproj.tr_pode_ver_modulo(v_uid, p_id) then
    perform imobproj.tr_erro('Este treinamento não é da sua trilha.');
  end if;
  return imobproj.tr_modulo_resumo(p_id, v_uid) || (
    select jsonb_build_object(
      'pergunta', m.pergunta, 'opcoes', m.opcoes,
      'baloes', coalesce((select jsonb_agg(jsonb_build_object('id', p.id, 'ordem', p.ordem, 'tela', p.tela, 'titulo', p.titulo,
                                                              'texto', p.texto, 'alvo', to_jsonb(p.alvo), 'posicao', p.posicao) order by p.ordem)
                          from imobproj.tr_passos p where p.modulo_id = m.id), '[]'))
    from imobproj.tr_modulos m where m.id = p_id);
end;
$$;

/** Guarda em que passo a pessoa parou (retoma em qualquer computador). Não desfaz a conclusão. */
create or replace function imobproj.tr_progresso_salvar(p_modulo bigint, p_passo int)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := imobproj.tr_exigir_login();
  v_total int;
begin
  if not imobproj.tr_pode_ver_modulo(v_uid, p_modulo) then
    perform imobproj.tr_erro('Este treinamento não é da sua trilha.');
  end if;
  select count(*) into v_total from imobproj.tr_passos p where p.modulo_id = p_modulo;
  insert into imobproj.tr_progresso (usuario_id, modulo_id, passo_atual)
  values (v_uid, p_modulo, least(greatest(coalesce(p_passo, 0), 0), v_total))
  on conflict (usuario_id, modulo_id) do update set passo_atual = excluded.passo_atual, atualizado_em = now();
end;
$$;

/** Responde a pergunta final. Acertou: o módulo fica concluído. O gabarito é conferido aqui, nunca vai para a tela. */
create or replace function imobproj.tr_responder(p_modulo bigint, p_opcao int)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := imobproj.tr_exigir_login();
  v_certo boolean;
  v_total int;
begin
  if not imobproj.tr_pode_ver_modulo(v_uid, p_modulo) then
    perform imobproj.tr_erro('Este treinamento não é da sua trilha.');
  end if;
  select m.resposta = p_opcao into v_certo from imobproj.tr_modulos m where m.id = p_modulo;
  v_certo := coalesce(v_certo, false);
  if v_certo then
    select count(*) into v_total from imobproj.tr_passos p where p.modulo_id = p_modulo;
    insert into imobproj.tr_progresso (usuario_id, modulo_id, passo_atual, concluido_em)
    values (v_uid, p_modulo, v_total, now())
    on conflict (usuario_id, modulo_id) do update
      set passo_atual = excluded.passo_atual, atualizado_em = now(),
          concluido_em = coalesce(imobproj.tr_progresso.concluido_em, excluded.concluido_em);
  end if;
  return jsonb_build_object('certo', v_certo,
    'concluidoEm', (select pr.concluido_em from imobproj.tr_progresso pr where pr.usuario_id = v_uid and pr.modulo_id = p_modulo));
end;
$$;

