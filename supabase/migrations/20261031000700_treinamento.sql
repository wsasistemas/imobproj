/** Cria ou altera um módulo e as trilhas em que ele aparece. */
create or replace function imobproj.tr_modulo_salvar(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := imobproj.tr_exigir_gestor();
  v_id bigint := nullif(p ->> 'id', '')::bigint;
begin
  if v_id is null then
    insert into imobproj.tr_modulos (codigo, titulo, descricao, papel, minutos, rota_demo, celular, pergunta, opcoes, resposta, status, ordem, atualizado_por)
    values ('novo_' || substr(md5(random()::text), 1, 12), btrim(p ->> 'titulo'), coalesce(p ->> 'descricao', ''), p ->> 'papel',
            coalesce((p ->> 'minutos')::int, 3), coalesce(nullif(p ->> 'rotaDemo', ''), '/'), coalesce((p ->> 'celular')::boolean, false),
            btrim(p ->> 'pergunta'), p -> 'opcoes', (p ->> 'resposta')::int, coalesce(p ->> 'status', 'rascunho'),
            coalesce((select max(ordem) from imobproj.tr_modulos), 0) + 1, v_uid)
    returning id into v_id;
    update imobproj.tr_modulos set codigo = 'm' || v_id where id = v_id;   -- código estável a partir do id
  else
    update imobproj.tr_modulos set
      titulo = btrim(p ->> 'titulo'), descricao = coalesce(p ->> 'descricao', ''), papel = p ->> 'papel',
      minutos = coalesce((p ->> 'minutos')::int, minutos), rota_demo = coalesce(nullif(p ->> 'rotaDemo', ''), rota_demo),
      celular = coalesce((p ->> 'celular')::boolean, celular), pergunta = btrim(p ->> 'pergunta'), opcoes = p -> 'opcoes',
      resposta = (p ->> 'resposta')::int, status = coalesce(p ->> 'status', status), atualizado_em = now(), atualizado_por = v_uid
    where id = v_id;
    if not found then
      perform imobproj.tr_erro('Módulo não encontrado.');
    end if;
  end if;
  if p ? 'trilhas' then
    delete from imobproj.tr_trilha_modulos tm
    where tm.modulo_id = v_id and tm.trilha_id not in (select (jsonb_array_elements_text(p -> 'trilhas'))::bigint);
    insert into imobproj.tr_trilha_modulos (trilha_id, modulo_id, ordem)
    select t::bigint, v_id, (select coalesce(max(x.ordem), 0) + 1 from imobproj.tr_trilha_modulos x where x.trilha_id = t::bigint)
    from jsonb_array_elements_text(p -> 'trilhas') t
    on conflict (trilha_id, modulo_id) do nothing;
  end if;
  return v_id;
end;
$$;

/** Cria ou altera um balão. Novo: entra no fim do módulo. */
create or replace function imobproj.tr_passo_salvar(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint := nullif(p ->> 'id', '')::bigint;
  v_modulo bigint := nullif(p ->> 'moduloId', '')::bigint;
  v_alvo numeric[] := array(select jsonb_array_elements_text(p -> 'alvo')::numeric);
begin
  perform imobproj.tr_exigir_gestor();
  if v_id is null then
    if not exists (select 1 from imobproj.tr_modulos m where m.id = v_modulo) then
      perform imobproj.tr_erro('Módulo não encontrado.');
    end if;
    insert into imobproj.tr_passos (modulo_id, ordem, tela, titulo, texto, alvo, posicao)
    values (v_modulo, (select coalesce(max(x.ordem), 0) + 1 from imobproj.tr_passos x where x.modulo_id = v_modulo),
            p ->> 'tela', btrim(p ->> 'titulo'), btrim(p ->> 'texto'), v_alvo, coalesce(nullif(p ->> 'posicao', ''), 'auto'))
    returning id into v_id;
  else
    update imobproj.tr_passos set
      tela = p ->> 'tela', titulo = btrim(p ->> 'titulo'), texto = btrim(p ->> 'texto'), alvo = v_alvo,
      posicao = coalesce(nullif(p ->> 'posicao', ''), 'auto'), atualizado_em = now()
    where id = v_id
    returning modulo_id into v_modulo;
    if v_modulo is null then
      perform imobproj.tr_erro('Balão não encontrado.');
    end if;
  end if;
  update imobproj.tr_modulos set atualizado_em = now() where id = v_modulo;
  return v_id;
end;
$$;

create or replace function imobproj.tr_passo_excluir(p_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_modulo bigint;
begin
  perform imobproj.tr_exigir_gestor();
  delete from imobproj.tr_passos where id = p_id returning modulo_id into v_modulo;
  if v_modulo is null then
    perform imobproj.tr_erro('Balão não encontrado.');
  end if;
  -- Fecha o buraco na numeração.
  update imobproj.tr_passos p set ordem = x.n
  from (select id, row_number() over (order by ordem) as n from imobproj.tr_passos where modulo_id = v_modulo) x
  where p.id = x.id and p.ordem <> x.n;
end;
$$;

/** Nova ordem dos balões: a lista completa dos ids do módulo. */
create or replace function imobproj.tr_passos_reordenar(p_modulo bigint, p_ids bigint[])
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform imobproj.tr_exigir_gestor();
  if (select array_agg(id order by id) from imobproj.tr_passos where modulo_id = p_modulo)
     is distinct from (select array_agg(i order by i) from unnest(p_ids) i) then
    perform imobproj.tr_erro('A lista precisa ter todos os balões do módulo, uma vez cada.');
  end if;
  update imobproj.tr_passos p set ordem = x.n
  from unnest(p_ids) with ordinality as x (id, n)
  where p.id = x.id;
end;
$$;

/** Liga perfis a uma trilha (cada perfil segue uma trilha só; os que saem voltam para a padrão). */
create or replace function imobproj.tr_trilha_perfis_salvar(p_trilha bigint, p_perfis text[])
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform imobproj.tr_exigir_gestor();
  if not exists (select 1 from imobproj.tr_trilhas t where t.id = p_trilha) then
    perform imobproj.tr_erro('Trilha não encontrada.');
  end if;
  delete from imobproj.tr_trilha_perfis where trilha_id = p_trilha and perfil <> all (coalesce(p_perfis, '{}'));
  insert into imobproj.tr_trilha_perfis (trilha_id, perfil)
  select p_trilha, s from unnest(coalesce(p_perfis, '{}')) s
  on conflict (perfil) do update set trilha_id = excluded.trilha_id;
end;
$$;

/** Progresso por perfil: pessoas, quem concluiu tudo, quem está no meio e quem não começou. */
create or replace function imobproj.tr_progresso_por_perfil()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform imobproj.tr_exigir_gestor();
  return coalesce((
    select jsonb_agg(jsonb_build_object('perfil', g.perfil, 'nome', coalesce(pf.nome, 'Sem perfil'), 'trilha', t.nome, 'pessoas', g.pessoas,
                                        'concluiram', g.concluiram, 'andamento', g.andamento, 'naoComecaram', g.pessoas - g.concluiram - g.andamento)
                     order by pf.ordem nulls last)
    from (
      select p.perfil, p.trilha_id, count(*) as pessoas,
             count(*) filter (where e.total > 0 and e.feitos = e.total) as concluiram,
             count(*) filter (where e.mexeu and not (e.total > 0 and e.feitos = e.total)) as andamento
      from imobproj.tr_pessoas_trilha() p
      cross join lateral (
        select count(*) as total,
               count(*) filter (where pr.concluido_em is not null) as feitos,
               coalesce(bool_or(pr.usuario_id is not null), false) as mexeu
        from imobproj.tr_modulos_visiveis(p.trilha_id) as v (id)
        left join imobproj.tr_progresso pr on pr.modulo_id = v.id and pr.usuario_id = p.usuario_id) e
      group by p.perfil, p.trilha_id) g
    left join imobproj.perfis pf on pf.chave = g.perfil
    join imobproj.tr_trilhas t on t.id = g.trilha_id), '[]');
end;
$$;

/** "Ver pessoas" de um perfil (null = sem perfil): cada módulo da trilha com passo atual e conclusão. */
create or replace function imobproj.tr_progresso_pessoas(p_perfil text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform imobproj.tr_exigir_gestor();
  return coalesce((
    select jsonb_agg(jsonb_build_object('usuarioId', p.usuario_id, 'nome', p.nome,
                     'modulos', coalesce((select jsonb_agg(jsonb_build_object('id', v.id, 'titulo', m.titulo, 'passoAtual', coalesce(pr.passo_atual, 0),
                                                                             'passos', (select count(*) from imobproj.tr_passos x where x.modulo_id = v.id),
                                                                             'concluidoEm', pr.concluido_em))
                                          from imobproj.tr_modulos_visiveis(p.trilha_id) as v (id)
                                          join imobproj.tr_modulos m on m.id = v.id
                                          left join imobproj.tr_progresso pr on pr.modulo_id = v.id and pr.usuario_id = p.usuario_id), '[]'))
                     order by p.nome)
    from imobproj.tr_pessoas_trilha() p
    where p.perfil is not distinct from p_perfil), '[]');
end;
$$;

