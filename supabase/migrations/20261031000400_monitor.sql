-- =============================================================================
-- IMOBPROJ — Fase 4: Monitor de atendimento (docs/PLANO-implantacao-final.md)
-- Migration ADITIVA: só create ... if not exists / add column if not exists / create or replace.
--
-- Atendimento = uma passagem de uma conversa (wa_groups) pela fila de um setor: entra na fila quando o cliente
-- escreve e não há atendimento aberto; alguém assume (ou a distribuição automática entrega); encerra.
-- O openwa-webhook chama imobproj.fn_atendimento_mensagem() depois de gravar cada mensagem recebida.
--
-- Definições dos indicadores (as mesmas do Monitor do imobdesk):
--   atendida          atendimento encerrado no período que alguém assumiu
--   resolvida no 1º   atendida sem transferência, sem voltar à fila e sem o cliente voltar em 24 h
--   fora do horário   entrou na fila com o setor fechado ou sem atendente online
--   espera            da entrada na fila até alguém assumir
--   atendimento       de assumir até encerrar
--
-- Quem monitora (imobproj.fn_monitor_setores): super admin e perfil Gerente veem todos os setores; o gestor
-- do setor e quem está numa equipe do setor veem só esses setores. Sempre exige "ver" em atendimento_monitor.
-- =============================================================================

create table if not exists imobproj.atendimentos (
  id                       uuid primary key default gen_random_uuid(),
  ticket                   bigint generated by default as identity (start with 1001) unique,
  setor_id                 uuid not null references imobproj.setores (id) on delete cascade,
  group_id                 uuid not null references imobproj.wa_groups (id) on delete cascade,
  project_id               uuid references imobproj.projects (id) on delete cascade,
  cliente_nome             text,
  cliente_telefone         text,
  atendente_id             uuid references imobproj.profiles (id) on delete set null,
  status                   text not null default 'fila' check (status in ('fila', 'atendimento', 'encerrado')),
  entrou_fila_em           timestamptz not null default now(),
  assumido_em              timestamptz,
  encerrado_em             timestamptz,
  encerrado_por            uuid references imobproj.profiles (id) on delete set null,
  transferencias           integer not null default 0 check (transferencias >= 0),
  devolvido_fila           boolean not null default false,
  reaberto_em_24h          boolean not null default false,
  fora_horario             boolean not null default false,
  ultima_previa            text,
  ultima_msg_cliente_em    timestamptz,
  ultima_msg_atendente_em  timestamptz,
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  constraint atendimentos_encerrado_chk check (status <> 'encerrado' or encerrado_em is not null)
);
-- Uma conversa tem no máximo um atendimento aberto.
create unique index if not exists atendimentos_aberto_unq on imobproj.atendimentos (group_id) where status <> 'encerrado';
create index if not exists atendimentos_setor_status_idx on imobproj.atendimentos (setor_id, status);
create index if not exists atendimentos_atendente_idx on imobproj.atendimentos (atendente_id) where status = 'atendimento';
create index if not exists atendimentos_encerrado_idx on imobproj.atendimentos (setor_id, encerrado_em);

-- Status de quem atende: online (com sinal recente da tela) e pausa.
create table if not exists imobproj.atendente_status (
  user_id        uuid primary key references imobproj.profiles (id) on delete cascade,
  online         boolean not null default false,
  pausa          boolean not null default false,
  apto           boolean not null default true,
  atualizado_em  timestamptz not null default now()
);

do $$
begin
