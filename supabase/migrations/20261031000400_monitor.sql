-- Números de uma janela [ini, fim) (interna).
create or replace function imobproj.fn_indicadores_janela(p_ini timestamptz, p_fim timestamptz, p_setores uuid[])
returns jsonb
language sql
stable
security definer
set search_path = imobproj
as $$
  with t as (select * from imobproj.atendimentos a where a.setor_id = any (p_setores)),
  enc as (select * from t where t.encerrado_em >= p_ini and t.encerrado_em < p_fim and t.assumido_em is not null)
  select jsonb_build_object(
    'atendidas', (select count(*) from enc),
    'resolvidas1o', (select count(*) from enc where enc.transferencias = 0 and not enc.devolvido_fila and not enc.reaberto_em_24h),
    'foraHorario', (select count(*) from t where t.entrou_fila_em >= p_ini and t.entrou_fila_em < p_fim and t.fora_horario),
    'esperaMediaSeg', (select round(avg(extract(epoch from (t.assumido_em - t.entrou_fila_em)))) from t
                        where t.assumido_em >= p_ini and t.assumido_em < p_fim),
    'atendimentoMedioSeg', (select round(avg(extract(epoch from (enc.encerrado_em - enc.assumido_em)))) from enc)
  );
$$;

-- p_periodo: hoje | semana | mes. O anterior é a mesma duração a partir do início do período anterior
-- (ex.: "este mês até agora" × "mês passado até o mesmo dia e hora"). p_agora existe para os testes.
create or replace function imobproj.monitor_indicadores(p_periodo text default 'mes', p_setor uuid default null, p_agora timestamptz default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = imobproj
as $$
declare
  v_setores uuid[] := imobproj.fn_monitor_setores(p_setor);
  v_unidade text := case p_periodo when 'hoje' then 'day' when 'semana' then 'week' when 'mes' then 'month' end;
  v_tz text := 'America/Sao_Paulo';
  v_agora timestamptz := coalesce(p_agora, now());
  v_ini timestamptz;
  v_ini_ant timestamptz;
  v_dur interval;
begin
  if v_unidade is null then
    raise exception 'Período inválido (hoje, semana ou mes).' using errcode = '22023';
  end if;
  v_ini := date_trunc(v_unidade, v_agora at time zone v_tz) at time zone v_tz;
  v_dur := v_agora - v_ini;
  v_ini_ant := date_trunc(v_unidade, (v_ini - interval '1 second') at time zone v_tz) at time zone v_tz;
  return jsonb_build_object(
    'inicio', v_ini,
    -- O fim da janela atual inclui o próprio instante (encerrado agora conta).
    'atual', imobproj.fn_indicadores_janela(v_ini, v_agora + interval '1 millisecond', v_setores),
    'anterior', imobproj.fn_indicadores_janela(v_ini_ant, v_ini_ant + v_dur, v_setores)
  );
end;
$$;

-- Acompanhamento de atendentes: online = sinal da tela nos últimos 5 min; disponível = apto, sem pausa, online e
-- abaixo do limite do setor.
create or replace function imobproj.monitor_atendentes(p_setor uuid default null)
returns table (
  usuario_id uuid, nome text, setor_id uuid, setor_nome text, online boolean, apto boolean, pausa boolean,
  em_atendimento integer, limite integer, atendidas_hoje integer, tempo_medio_seg numeric
)
language sql
stable
security definer
set search_path = imobproj
as $$
  with hoje as (select date_trunc('day', now() at time zone 'America/Sao_Paulo') at time zone 'America/Sao_Paulo' as ini)
  select u.user_id, p.nome, s.id, s.nome,
         imobproj.fn_atendente_online(u.user_id),
         coalesce(st.apto, true), coalesce(st.pausa, false),
         (select count(*)::int from imobproj.atendimentos a where a.atendente_id = u.user_id and a.status = 'atendimento'),
         coalesce(r.limite_por_atendente, 5),
         (select count(*)::int from imobproj.atendimentos a, hoje
           where a.atendente_id = u.user_id and a.encerrado_em >= hoje.ini and a.assumido_em is not null),
         (select round(avg(extract(epoch from (a.encerrado_em - a.assumido_em)))) from imobproj.atendimentos a, hoje
           where a.atendente_id = u.user_id and a.encerrado_em >= hoje.ini and a.assumido_em is not null)
    from imobproj.setores s
    cross join lateral imobproj.fn_atendentes_do_setor(s.id) as u(user_id)
    join imobproj.profiles p on p.id = u.user_id
    left join imobproj.atendente_status st on st.user_id = u.user_id
    left join imobproj.setor_regras r on r.setor_id = s.id
   where s.id = any (imobproj.fn_monitor_setores(p_setor))
   order by s.nome, p.nome;
$$;

-- Conversas aguardando (fila) e em atendimento, com o ticket e os tempos.
create or replace function imobproj.monitor_conversas(p_setor uuid default null)
returns table (
  atendimento_id uuid, ticket bigint, setor_id uuid, setor_nome text, group_id uuid, project_id uuid, grupo_nome text,
  cliente text, telefone text, numero text, status text, ultima_previa text, entrou_fila_em timestamptz,
  atendente_id uuid, atendente_nome text, assumido_em timestamptz,
  ultima_msg_cliente_em timestamptz, ultima_msg_atendente_em timestamptz
)
language sql
stable
security definer
set search_path = imobproj
as $$
  select a.id, a.ticket, a.setor_id, s.nome, a.group_id, a.project_id, g.nome,
         coalesce(a.cliente_nome, g.nome), a.cliente_telefone, ws.numero, a.status, a.ultima_previa, a.entrou_fila_em,
         a.atendente_id, p.nome, a.assumido_em, a.ultima_msg_cliente_em, a.ultima_msg_atendente_em
    from imobproj.atendimentos a
    join imobproj.setores s on s.id = a.setor_id
    join imobproj.wa_groups g on g.id = a.group_id
    left join imobproj.wa_sessions ws on ws.id = g.session_id
    left join imobproj.profiles p on p.id = a.atendente_id
   where a.setor_id = any (imobproj.fn_monitor_setores(p_setor)) and a.status in ('fila', 'atendimento')
   order by a.status, coalesce(a.entrou_fila_em, a.assumido_em);
$$;

