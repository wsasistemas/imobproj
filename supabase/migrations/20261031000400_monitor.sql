do $$
declare
  f text;
begin
  foreach f in array array[
    'imobproj.fn_monitor_setores(uuid)', 'imobproj.fn_pode_atender(uuid, uuid)', 'imobproj.fn_pode_gerir_setor(uuid)',
    'imobproj.fn_atendente_online(uuid)',
    'imobproj.at_assumir(uuid)', 'imobproj.at_assumir_conversa(uuid)', 'imobproj.at_transferir(uuid, uuid, uuid)',
    'imobproj.at_devolver_fila(uuid)', 'imobproj.at_encerrar(uuid)', 'imobproj.at_meu_status(boolean, boolean)',
    'imobproj.monitor_indicadores(text, uuid, timestamptz)', 'imobproj.monitor_atendentes(uuid)',
    'imobproj.monitor_conversas(uuid)'
  ] loop
    execute format('revoke execute on function %s from public, anon', f);
    execute format('grant execute on function %s to authenticated, service_role', f);
  end loop;
  foreach f in array array[
    'imobproj.fn_atendimento_mensagem(uuid)', 'imobproj.fn_distribuir_fila(uuid)',
    'imobproj.fn_indicadores_janela(timestamptz, timestamptz, uuid[])', 'imobproj.fn_atendentes_do_setor(uuid)',
    'imobproj.fn_autor_interno(uuid)'
  ] loop
    execute format('revoke execute on function %s from public, anon, authenticated', f);
    execute format('grant execute on function %s to service_role', f);
  end loop;
end $$;

-- -----------------------------------------------------------------------------
-- RLS: leitura de quem monitora o setor, de quem está atendendo e de quem vê o projeto da conversa.
-- Escrita só pelas funções acima (sem insert/update/delete para authenticated).
-- -----------------------------------------------------------------------------
alter table imobproj.atendimentos enable row level security;
alter table imobproj.atendente_status enable row level security;

revoke all on imobproj.atendimentos, imobproj.atendente_status from anon;
grant select on imobproj.atendimentos, imobproj.atendente_status to authenticated;
grant all on imobproj.atendimentos, imobproj.atendente_status to service_role;

drop policy if exists atendimentos_select on imobproj.atendimentos;
create policy atendimentos_select on imobproj.atendimentos for select to authenticated
  using (
    atendente_id = (select auth.uid())
    or setor_id in (select unnest(imobproj.fn_monitor_setores()))
    or imobproj.fn_can_view_project(project_id)
  );

drop policy if exists atendente_status_select on imobproj.atendente_status;
create policy atendente_status_select on imobproj.atendente_status for select to authenticated using (true);

-- -----------------------------------------------------------------------------
-- Realtime (aditivo): o Monitor e a tela de Conversas acompanham as mudanças ao vivo.
-- -----------------------------------------------------------------------------
do $$
declare
  t text;
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;
  foreach t in array array['atendimentos', 'atendente_status']
  loop
    if not exists (select 1 from pg_publication_tables
                    where pubname = 'supabase_realtime' and schemaname = 'imobproj' and tablename = t) then
      execute format('alter publication supabase_realtime add table imobproj.%I', t);
    end if;
  end loop;
end $$;

-- -----------------------------------------------------------------------------
-- Permissão do menu novo nos perfis iniciais (aditivo): gerente vê todos os setores; atendente vê os setores
-- das equipes dele (fn_monitor_setores). Os demais perfis não veem.
-- -----------------------------------------------------------------------------
insert into imobproj.perfil_permissoes (perfil, menu, ver, criar, editar, excluir, aprovar)
select v.perfil, v.menu, v.ver, v.criar, v.editar, v.excluir, v.aprovar
from (values
  ('gerente',   'atendimento_monitor', true, false, true, false, false),
  ('atendente', 'atendimento_monitor', true, false, true, false, false)
) as v(perfil, menu, ver, criar, editar, excluir, aprovar)
where exists (select 1 from imobproj.perfis p where p.chave = v.perfil)
on conflict (perfil, menu) do nothing;

notify pgrst, 'reload schema';
