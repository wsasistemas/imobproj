-- Online de verdade: marcou online e a tela mandou sinal nos últimos 5 minutos.
create or replace function imobproj.fn_atendente_online(p_user uuid)
returns boolean
language sql
stable
security definer
set search_path = imobproj
as $$
  select coalesce((select a.online and a.atualizado_em > now() - interval '5 minutes'
                     from imobproj.atendente_status a where a.user_id = p_user), false);
$$;

-- Atendentes de um setor: quem está numa equipe do setor e atende no WhatsApp.
create or replace function imobproj.fn_atendentes_do_setor(p_setor uuid)
returns setof uuid
language sql
stable
security definer
set search_path = imobproj
as $$
  select distinct tm.user_id
    from imobproj.teams t
    join imobproj.team_members tm on tm.team_id = t.id
    join imobproj.profiles p on p.id = tm.user_id and p.ativo and p.atende_whatsapp
   where t.setor_id = p_setor and t.ativo;
$$;

-- Autor interno (equipe da executora/prestador, quem atende ou super admin): mensagem dele não abre atendimento.
create or replace function imobproj.fn_autor_interno(p_user uuid)
returns boolean
language sql
stable
security definer
set search_path = imobproj
as $$
  select coalesce((
    select p.is_super_admin or p.atende_whatsapp or coalesce(o.tipo in ('executora', 'prestador'), false)
      from imobproj.profiles p
      left join imobproj.organizations o on o.id = p.organization_id
     where p.id = p_user), false);
$$;

-- Setores que o usuário logado monitora (p_setor null = todos os permitidos).
create or replace function imobproj.fn_monitor_setores(p_setor uuid default null)
returns uuid[]
language sql
stable
security definer
set search_path = imobproj
as $$
  select coalesce(array_agg(s.id order by s.nome), '{}')
    from imobproj.setores s
   where (p_setor is null or s.id = p_setor)
     and (select auth.uid()) is not null
     and imobproj.pode('atendimento_monitor', 'ver')
     and (
       imobproj.fn_is_super_admin()
       or exists (select 1 from imobproj.profiles p where p.id = (select auth.uid()) and p.perfil = 'gerente')
       or s.gestor_id = (select auth.uid())
       or exists (select 1 from imobproj.teams t join imobproj.team_members tm on tm.team_id = t.id
                   where t.setor_id = s.id and tm.user_id = (select auth.uid()))
     );
$$;

-- Pode atender conversas do setor (assumir/receber transferência)?
create or replace function imobproj.fn_pode_atender(p_setor uuid, p_user uuid default null)
returns boolean
language sql
stable
security definer
set search_path = imobproj
as $$
  select coalesce(p_user, (select auth.uid())) is not null and (
    exists (select 1 from imobproj.profiles p where p.id = coalesce(p_user, (select auth.uid()))
              and p.ativo and (p.is_super_admin or p.perfil = 'gerente'))
    or exists (select 1 from imobproj.setores s where s.id = p_setor and s.gestor_id = coalesce(p_user, (select auth.uid())))
    or exists (select 1 from imobproj.teams t join imobproj.team_members tm on tm.team_id = t.id
                where t.setor_id = p_setor and tm.user_id = coalesce(p_user, (select auth.uid())))
  );
$$;

-- Pode gerir (transferir/encerrar o atendimento de outra pessoa)? Super admin, perfil Gerente ou gestor do setor.
create or replace function imobproj.fn_pode_gerir_setor(p_setor uuid)
returns boolean
language sql
stable
security definer
set search_path = imobproj
as $$
  select imobproj.fn_is_super_admin()
      or exists (select 1 from imobproj.profiles p where p.id = (select auth.uid()) and p.perfil = 'gerente')
      or exists (select 1 from imobproj.setores s where s.id = p_setor and s.gestor_id = (select auth.uid()));
$$;

-- -----------------------------------------------------------------------------
-- Distribuição automática: entrega a fila do setor a quem está disponível (online, sem pausa, apto e abaixo do
-- limite), começando por quem tem menos conversas. Só com o setor aberto e a distribuição ligada.
-- -----------------------------------------------------------------------------
create or replace function imobproj.fn_distribuir_fila(p_setor uuid)
returns integer
language plpgsql
security definer
set search_path = imobproj
as $$
declare
  v_regra imobproj.setor_regras;
  v_at record;
  v_user uuid;
  v_entregues integer := 0;
begin
  select * into v_regra from imobproj.setor_regras where setor_id = p_setor;
  if not found or not v_regra.distribuicao_automatica or not imobproj.fn_setor_aberto(p_setor) then
    return 0;
  end if;
  for v_at in
    select a.id from imobproj.atendimentos a
     where a.setor_id = p_setor and a.status = 'fila'
     order by a.entrou_fila_em
     for update skip locked
  loop
    select u.user_id into v_user
      from imobproj.fn_atendentes_do_setor(p_setor) as u(user_id)
      join imobproj.atendente_status st on st.user_id = u.user_id
     where imobproj.fn_atendente_online(u.user_id) and not st.pausa and st.apto
       and (select count(*) from imobproj.atendimentos x where x.atendente_id = u.user_id and x.status = 'atendimento')
           < v_regra.limite_por_atendente
     order by (select count(*) from imobproj.atendimentos x where x.atendente_id = u.user_id and x.status = 'atendimento'),
              (select max(x.assumido_em) from imobproj.atendimentos x where x.atendente_id = u.user_id) nulls first
     limit 1;
    exit when v_user is null;
    update imobproj.atendimentos
       set atendente_id = v_user, status = 'atendimento', assumido_em = coalesce(assumido_em, now())
     where id = v_at.id;
    v_entregues := v_entregues + 1;
    v_user := null;
  end loop;
  return v_entregues;
end;
$$;

-- -----------------------------------------------------------------------------
-- Mensagem gravada → atendimento. Chamada pelo openwa-webhook (service_role) depois de inserir a mensagem.
-- Cliente escreveu e não há atendimento aberto: abre na fila (fora do horário se o setor estava fechado ou sem
-- ninguém online) e tenta distribuir. Já aberto: atualiza a prévia e o horário da última mensagem.
-- Devolve o id do atendimento (null quando a conversa não tem setor ou é mensagem de sistema).
-- -----------------------------------------------------------------------------
create or replace function imobproj.fn_atendimento_mensagem(p_message_id uuid)
returns uuid
language plpgsql
security definer
set search_path = imobproj
as $$
declare
  v_m record;
  v_setor uuid;
  v_id uuid;
  v_cliente boolean;
  v_nome text;
  v_fora boolean;
begin
  select m.id, m.group_id, m.direction, m.author_phone, m.author_user_id, m.body, m.media_path, m.created_at,
         g.setor_id, g.session_id, g.project_id
    into v_m
    from imobproj.wa_messages m
    join imobproj.wa_groups g on g.id = m.group_id
   where m.id = p_message_id;
  if not found then
    return null;
  end if;

  v_setor := coalesce(v_m.setor_id, imobproj.fn_rotear_conversa(v_m.group_id, v_m.session_id));
  if v_setor is null then
    return null;
  end if;

  v_cliente := v_m.direction = 'in' and v_m.author_phone is not null and not imobproj.fn_autor_interno(v_m.author_user_id);

  select id into v_id from imobproj.atendimentos where group_id = v_m.group_id and status <> 'encerrado';

  if v_id is null then
    if not v_cliente then
      return null;
    end if;
    -- O cliente voltou em menos de 24 h: o atendimento anterior deixa de contar como resolvido no 1º.
    update imobproj.atendimentos
       set reaberto_em_24h = true
     where id = (select a.id from imobproj.atendimentos a
                  where a.group_id = v_m.group_id and a.status = 'encerrado'
                    and a.encerrado_em > v_m.created_at - interval '24 hours'
                  order by a.encerrado_em desc limit 1);

    select coalesce(
             (select p.nome from imobproj.profiles p where p.id = v_m.author_user_id),
             (select c.nome from imobproj.organization_contacts c
               where regexp_replace(coalesce(c.telefone_whatsapp, ''), '\D', '', 'g') = v_m.author_phone limit 1),
             (select coalesce(o.nome_fantasia, o.nome) from imobproj.projects pr
                join imobproj.organizations o on o.id = pr.cliente_org_id where pr.id = v_m.project_id))
      into v_nome;

    v_fora := not imobproj.fn_setor_aberto(v_setor, v_m.created_at)
              or (v_m.created_at > now() - interval '5 minutes'
                  and not exists (select 1 from imobproj.fn_atendentes_do_setor(v_setor) as u(user_id)
                                   where imobproj.fn_atendente_online(u.user_id)));

    insert into imobproj.atendimentos (setor_id, group_id, project_id, cliente_nome, cliente_telefone, status,
                                       entrou_fila_em, fora_horario, ultima_previa, ultima_msg_cliente_em)
    values (v_setor, v_m.group_id, v_m.project_id, v_nome, v_m.author_phone, 'fila', v_m.created_at, v_fora,
            left(coalesce(nullif(v_m.body, ''), case when v_m.media_path is not null then 'Arquivo' end), 140),
            v_m.created_at)
    on conflict do nothing
    returning id into v_id;

    if v_id is null then
      select id into v_id from imobproj.atendimentos where group_id = v_m.group_id and status <> 'encerrado';
    else
      perform imobproj.fn_distribuir_fila(v_setor);
    end if;
    return v_id;
  end if;

  update imobproj.atendimentos
     set ultima_previa = left(coalesce(nullif(v_m.body, ''), case when v_m.media_path is not null then 'Arquivo' end, ultima_previa), 140),
         ultima_msg_cliente_em   = case when v_cliente then greatest(coalesce(ultima_msg_cliente_em, v_m.created_at), v_m.created_at) else ultima_msg_cliente_em end,
         ultima_msg_atendente_em = case when not v_cliente then greatest(coalesce(ultima_msg_atendente_em, v_m.created_at), v_m.created_at) else ultima_msg_atendente_em end
   where id = v_id;
  return v_id;
end;
$$;

-- Resposta enviada pelo portal (direction 'out'): marca o horário da última mensagem do atendente.
create or replace function imobproj.fn_wa_messages_atendimento()
returns trigger
language plpgsql
security definer
set search_path = imobproj
as $$
begin
  if new.direction = 'out' then
    update imobproj.atendimentos
       set ultima_msg_atendente_em = new.created_at,
           ultima_previa = left(coalesce(nullif(new.body, ''), ultima_previa), 140)
     where group_id = new.group_id and status <> 'encerrado';
  end if;
  return new;
exception when others then
  raise warning 'imobproj.fn_wa_messages_atendimento: %', sqlerrm;
  return new;
end;
$$;

drop trigger if exists trg_wa_messages_atendimento on imobproj.wa_messages;
create trigger trg_wa_messages_atendimento after insert on imobproj.wa_messages
  for each row execute function imobproj.fn_wa_messages_atendimento();

-- -----------------------------------------------------------------------------
-- Ações de quem atende (RPC; a tabela não aceita escrita direta)
-- -----------------------------------------------------------------------------
create or replace function imobproj.at_assumir(p_atendimento uuid)
returns void
language plpgsql
security definer
set search_path = imobproj
as $$
declare
  v imobproj.atendimentos;
begin
  select * into v from imobproj.atendimentos where id = p_atendimento for update;
  if not found then
    raise exception 'Atendimento não encontrado.' using errcode = 'P0002';
  end if;
  if v.status = 'encerrado' then
    raise exception 'Este atendimento já foi encerrado.' using errcode = 'P0001';
  end if;
  if not imobproj.fn_pode_atender(v.setor_id) then
    raise exception 'Você não atende o setor desta conversa.' using errcode = '42501';
  end if;
  if v.status = 'atendimento' and v.atendente_id is not null and v.atendente_id <> (select auth.uid()) then
    raise exception 'Outra pessoa já assumiu esta conversa.' using errcode = 'P0001';
  end if;
  update imobproj.atendimentos
     set atendente_id = (select auth.uid()), status = 'atendimento', assumido_em = coalesce(assumido_em, now())
   where id = p_atendimento;
end;
$$;

-- Pela tela de Conversas: assume o atendimento aberto do grupo ou abre um (no setor do grupo) e assume.
create or replace function imobproj.at_assumir_conversa(p_group_id uuid)
returns uuid
language plpgsql
security definer
set search_path = imobproj
as $$
declare
  v_id uuid;
  v_setor uuid;
  v_projeto uuid;
begin
  select setor_id, project_id into v_setor, v_projeto from imobproj.wa_groups where id = p_group_id;
  if not found then
    raise exception 'Conversa não encontrada.' using errcode = 'P0002';
  end if;
  if v_setor is null then
    raise exception 'Esta conversa não está na fila de nenhum setor. Ligue o número a um setor em Setores e números.' using errcode = 'P0001';
  end if;
  if not imobproj.fn_can_view_project(v_projeto) and not imobproj.fn_pode_atender(v_setor) then
    raise exception 'Você não tem acesso a esta conversa.' using errcode = '42501';
  end if;
  select id into v_id from imobproj.atendimentos where group_id = p_group_id and status <> 'encerrado';
  if v_id is null then
    if not imobproj.fn_pode_atender(v_setor) then
      raise exception 'Você não atende o setor desta conversa.' using errcode = '42501';
    end if;
    insert into imobproj.atendimentos (setor_id, group_id, project_id, status, entrou_fila_em)
    values (v_setor, p_group_id, v_projeto, 'fila', now())
    on conflict do nothing
    returning id into v_id;
    if v_id is null then
      select id into v_id from imobproj.atendimentos where group_id = p_group_id and status <> 'encerrado';
    end if;
  end if;
  perform imobproj.at_assumir(v_id);
  return v_id;
end;
$$;

-- Transferir para outra pessoa (do mesmo setor) e/ou para outro setor (volta à fila do destino).
create or replace function imobproj.at_transferir(p_atendimento uuid, p_atendente uuid default null, p_setor uuid default null)
returns void
language plpgsql
security definer
set search_path = imobproj
as $$
declare
  v imobproj.atendimentos;
  v_destino uuid;
begin
  select * into v from imobproj.atendimentos where id = p_atendimento for update;
  if not found then
    raise exception 'Atendimento não encontrado.' using errcode = 'P0002';
  end if;
  if v.status = 'encerrado' then
    raise exception 'Este atendimento já foi encerrado.' using errcode = 'P0001';
  end if;
  if p_atendente is null and p_setor is null then
    raise exception 'Escolha a pessoa ou o setor de destino.' using errcode = '22023';
  end if;
  if not (v.atendente_id = (select auth.uid()) or imobproj.fn_pode_gerir_setor(v.setor_id)) then
    raise exception 'Só quem está atendendo ou a gestão do setor pode transferir.' using errcode = '42501';
  end if;
  v_destino := coalesce(p_setor, v.setor_id);
  if p_setor is not null and not exists (select 1 from imobproj.setores where id = p_setor and ativo) then
    raise exception 'Setor de destino inválido ou inativo.' using errcode = '22023';
  end if;
  if p_atendente is not null and not imobproj.fn_pode_atender(v_destino, p_atendente) then
    raise exception 'A pessoa escolhida não atende o setor de destino.' using errcode = '22023';
  end if;
  update imobproj.atendimentos
     set setor_id = v_destino,
         atendente_id = p_atendente,
         status = case when p_atendente is null then 'fila' else 'atendimento' end,
         assumido_em = case when p_atendente is null then assumido_em else coalesce(assumido_em, now()) end,
         transferencias = transferencias + 1
   where id = p_atendimento;
  if p_atendente is null then
    perform imobproj.fn_distribuir_fila(v_destino);
  end if;
end;
$$;

create or replace function imobproj.at_devolver_fila(p_atendimento uuid)
returns void
language plpgsql
security definer
set search_path = imobproj
as $$
declare
  v imobproj.atendimentos;
begin
  select * into v from imobproj.atendimentos where id = p_atendimento for update;
  if not found or v.status <> 'atendimento' then
    raise exception 'Só um atendimento em andamento volta para a fila.' using errcode = 'P0001';
  end if;
  if not (v.atendente_id = (select auth.uid()) or imobproj.fn_pode_gerir_setor(v.setor_id)) then
    raise exception 'Só quem está atendendo ou a gestão do setor pode devolver à fila.' using errcode = '42501';
  end if;
  update imobproj.atendimentos
     set status = 'fila', atendente_id = null, devolvido_fila = true
   where id = p_atendimento;
end;
$$;

create or replace function imobproj.at_encerrar(p_atendimento uuid)
returns void
language plpgsql
security definer
set search_path = imobproj
as $$
declare
  v imobproj.atendimentos;
begin
  select * into v from imobproj.atendimentos where id = p_atendimento for update;
  if not found then
    raise exception 'Atendimento não encontrado.' using errcode = 'P0002';
  end if;
  if v.status = 'encerrado' then
    return;
  end if;
  if not (v.atendente_id = (select auth.uid()) or imobproj.fn_pode_gerir_setor(v.setor_id)) then
    raise exception 'Só quem está atendendo ou a gestão do setor pode encerrar.' using errcode = '42501';
  end if;
  update imobproj.atendimentos
     set status = 'encerrado', encerrado_em = now(), encerrado_por = (select auth.uid()),
         assumido_em = coalesce(assumido_em, case when atendente_id is not null then now() end)
   where id = p_atendimento;
  perform imobproj.fn_distribuir_fila(v.setor_id);
end;
$$;

-- Meu status (online/pausa). Sem argumentos = sinal de vida da tela aberta.
-- Ficar online ou sair da pausa puxa a fila dos setores da pessoa.
create or replace function imobproj.at_meu_status(p_online boolean default null, p_pausa boolean default null)
returns imobproj.atendente_status
language plpgsql
security definer
set search_path = imobproj
as $$
declare
  v imobproj.atendente_status;
  s uuid;
begin
  if (select auth.uid()) is null then
    raise exception 'Sessão expirada.' using errcode = '42501';
  end if;
  insert into imobproj.atendente_status as a (user_id, online, pausa, atualizado_em)
  values ((select auth.uid()), coalesce(p_online, false), coalesce(p_pausa, false), now())
  on conflict (user_id) do update
     set online = coalesce(p_online, a.online),
         pausa = case when coalesce(p_online, a.online) then coalesce(p_pausa, a.pausa) else false end,
         atualizado_em = now()
  returning * into v;
  if (p_online is true or p_pausa is false) and v.online and not v.pausa then
    for s in select distinct t.setor_id from imobproj.teams t join imobproj.team_members tm on tm.team_id = t.id
              where tm.user_id = (select auth.uid()) and t.setor_id is not null
    loop
      perform imobproj.fn_distribuir_fila(s);
    end loop;
  end if;
  return v;
end;
$$;

